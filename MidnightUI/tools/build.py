#!/usr/bin/env python3
"""Bundler for MidnightUI.

The library is written as normal Roblox modules (`require(script.Parent.X)`),
which is what you want when syncing it into Studio with Rojo. This script
turns that tree into a single self-contained Luau file for the people who
prefer one `loadstring`-able script.

Usage:
    python3 tools/build.py                 # -> dist/Midnight.luau
    python3 tools/build.py --tests         # -> tests/.build/bundle.luau
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

REQUIRE_RE = re.compile(r"require\((?:\s*)(script(?:\.[A-Za-z_][A-Za-z0-9_]*)*)(?:\s*)\)")

BANNER = "--[[\n\t{name} — bundled build\n\tGenerated by tools/build.py — do not edit by hand.\n\tSource of truth lives in src/ (Rojo compatible modules).\n]]\n"


def module_id(path: Path) -> str:
    return path.relative_to(ROOT).with_suffix("").as_posix()


def discover(directories: list[str], extra_files: list[Path]) -> dict[str, Path]:
    modules: dict[str, Path] = {}

    for directory in directories:
        for path in sorted((ROOT / directory).rglob("*.luau")):
            modules[module_id(path)] = path

    for path in extra_files:
        modules[module_id(path)] = path

    return modules


def resolve_require(from_file: Path, expression: str) -> Path:
    node = from_file
    parts = expression.split(".")[1:]

    for part in parts:
        if part == "Parent":
            node = node.parent
            continue

        base = node if node.is_dir() else node.parent
        directory = base / part

        if directory.is_dir():
            node = directory
            continue

        target = base / f"{part}.luau"

        if not target.exists():
            raise FileNotFoundError(
                f"cannot resolve require({expression}) from {from_file.relative_to(ROOT)}"
            )

        node = target

    return node


def transform(path: Path, known: dict[str, Path]) -> str:
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines(keepends=True)
    output: list[str] = []

    for line in lines:
        if "require(" not in line:
            output.append(line)
            continue

        def replace(match: re.Match[str]) -> str:
            target = resolve_require(path, match.group(1))
            identifier = module_id(target)

            if identifier not in known:
                raise KeyError(f"{identifier} was not collected")

            return f'__req("{identifier}")'

        output.append(REQUIRE_RE.sub(replace, line))

    return "".join(output)


def build(entry: str, modules: dict[str, Path], order: list[str]) -> str:
    chunks: list[str] = []

    chunks.append("--!nocheck\n")
    chunks.append(BANNER.format(name=entry))
    chunks.append("local __modules = {}\n")
    chunks.append("local __cache = {}\n\n")
    chunks.append(
        "local function __req(id)\n"
        "\tlocal cached = __cache[id]\n"
        "\tif cached ~= nil then\n"
        "\t\treturn cached\n"
        "\tend\n\n"
        "\tlocal factory = __modules[id]\n"
        "\tif factory == nil then\n"
        '\t\terror("[MidnightUI] module not found: " .. tostring(id))\n'
        "\tend\n\n"
        "\tlocal value = factory()\n"
        "\t__cache[id] = value\n\n"
        "\treturn value\n"
        "end\n\n"
    )

    for identifier in order:
        path = modules[identifier]
        body = transform(path, modules)

        chunks.append(f'__modules["{identifier}"] = function()\n')
        chunks.append(body.rstrip("\n"))
        chunks.append("\nend\n\n")

    chunks.append(f'return __req("{entry}")\n')

    return "".join(chunks)


def main() -> int:
    parser = argparse.ArgumentParser(description="MidnightUI bundler")
    parser.add_argument("--tests", action="store_true", help="bundle the selftest instead of the library")
    parser.add_argument("--out", type=str, default=None, help="explicit output path")
    parser.add_argument("--entry", type=str, default=None, help="module id to use as the bundle entry, e.g. src/init")
    args = parser.parse_args()

    extras = [path for path in sorted((ROOT / "tests").glob("*.luau"))]

    if args.entry:
        entry = args.entry
        modules = discover(["src"], extras)
        output = Path(args.out) if args.out else ROOT / "tests" / ".build" / "bundle.luau"
    elif args.tests:
        modules = discover(["src"], extras)
        entry = "tests/Selftest"
        output = Path(args.out) if args.out else ROOT / "tests" / ".build" / "bundle.luau"
    else:
        modules = discover(["src"], [])
        entry = "src/init"
        output = Path(args.out) if args.out else ROOT / "dist" / "Midnight.luau"

    # deterministic order: dependency-free modules first, entry last
    order = sorted(identifier for identifier in modules if identifier != entry)
    order.append(entry)

    bundle = build(entry, modules, order)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(bundle, encoding="utf-8")

    print(f"bundled {len(modules)} modules -> {output.relative_to(ROOT)} ({len(bundle):,} bytes)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
